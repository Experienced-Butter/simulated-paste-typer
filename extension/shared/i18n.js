  function pickLocale() {
    var ui = '';
    try {
      if (typeof chrome !== 'undefined' && chrome.i18n && typeof chrome.i18n.getUILanguage === 'function') {
        ui = chrome.i18n.getUILanguage();
      }
    } catch (e) { /* ignore */ }
    if (!ui) {
      try {
        ui = (typeof navigator !== 'undefined' && (navigator.language || (navigator.languages && navigator.languages[0]))) || '';
      } catch (e) { /* ignore */ }
    }
    ui = String(ui || 'en').toLowerCase();
    if (ui.indexOf('zh') === 0) {
      if (/(tw|hk|mo|hant)/.test(ui)) return 'zh_TW';
      return 'zh_CN';
    }
    return 'en';
  }

  var locale = pickLocale();
  var dict = MSG[locale] || MSG.en;

  function t(key, subs) {
    var s = dict[key];
    if (s === undefined) s = MSG.zh_CN[key];
    if (s === undefined) s = MSG.en[key];
    if (s === undefined) return key;
    if (subs) {
      Object.keys(subs).forEach(function (k) {
        s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), String(subs[k]));
      });
    }
    return s;
  }

  function apply(root) {
    var doc = root || (typeof document !== 'undefined' ? document : null);
    if (!doc || !doc.querySelectorAll) return;
    var attrs = ['data-i18n', 'data-i18n-title', 'data-i18n-placeholder', 'data-i18n-aria-label'];
    attrs.forEach(function (attr) {
      var nodes = doc.querySelectorAll('[' + attr + ']');
      for (var i = 0; i < nodes.length; i++) {
        var el = nodes[i];
        var key = el.getAttribute(attr);
        if (!key) continue;
        var text = t(key);
        if (attr === 'data-i18n') el.textContent = text;
        else if (attr === 'data-i18n-title') el.setAttribute('title', text);
        else if (attr === 'data-i18n-placeholder') el.setAttribute('placeholder', text);
        else el.setAttribute('aria-label', text);
      }
    });
  }

  g.SPT_I18N = { locale: locale, t: t, apply: apply };
